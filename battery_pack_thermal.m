function battery_pack_thermal(varargin)
%BATTERY_PACK_THERMAL  Build + run a real Simscape Battery 100s2p thermal model.
%
%   battery_pack_thermal                      % build if needed, run, show viewer
%   battery_pack_thermal('Rebuild',true)      % force regeneration of the model
%   battery_pack_thermal('Run',false)         % build and open the model only
%   battery_pack_thermal('NPaPerMod',3,'NMod',3)   % small config, for a fast test
%
%   WHAT THIS BUILDS
%   ----------------
%   A genuine Simulink/Simscape model, battery_pack_100s2p.slx, containing
%   Simscape Battery module blocks generated by buildBattery from Battery
%   Builder objects and wired into a complete circuit:
%
%     * electrical : nMod modules in series, driven by a Controlled Current
%                    Source running a rest / CC-charge / rest / CC-discharge /
%                    rest duty cycle, with a Voltage Sensor across the pack.
%     * thermal    : every cell is an individual thermal node (Detailed model
%                    resolution).  Inside each module Simscape Battery builds
%                    cell-to-cell conduction AND radiation within each parallel
%                    assembly and between neighbouring parallel assemblies
%                    (orthogonal and diagonal pairs).  Each module exposes its
%                    two long faces as vectorised thermal nodes (XminH/XmaxH),
%                    and this script chains module k's XmaxH to module k+1's
%                    XminH.  That link is what closes the thermal network ACROSS
%                    module boundaries: the pack is one connected grid of
%                    coupled cell thermal nodes, 20 x 10 for the 100s2p default.
%     * cooling    : natural convection + radiation to still ambient air only.
%                    Every cell has its own thermal resistance to a single
%                    ambient node held at P.Tamb by a Temperature Source.
%                    That resistance is set per cell from how many neighbours
%                    shade it, so edge and corner cells run cooler than core
%                    cells.  There is no cooling plate and no coolant.
%
%   Files: this script, battery_pack_100s2p.slx, and a generated/ folder that
%   buildBattery fills with the Simscape component libraries the model links to.
%
%   Requires: Simulink, Simscape, Simscape Battery, Simscape Electrical.

%% ===================== 0. OPTIONS + PARAMETERS =====================
opt = struct('Rebuild', false, 'Run', true, 'NPaPerMod', 10, 'NMod', 10, ...
             'Open', true);
if mod(numel(varargin),2), error('Arguments must be name-value pairs.'); end
for i = 1:2:numel(varargin)
    f = char(varargin{i});
    if ~isfield(opt, f), error('Unknown option "%s".', f); end
    opt.(f) = varargin{i+1};
end

P = defaultParams(opt);

here   = fileparts(mfilename('fullpath'));
genDir = fullfile(here, 'generated');
mdl    = 'battery_pack_100s2p';     % must differ from this script's name
mdlF   = fullfile(here, [mdl '.slx']);

fprintf('=== %ds%dp 21700 pack: %d modules x %ds%dp = %d cells ===\n', ...
        P.Ns, P.Np, P.nMod, P.nPaPerMod, P.Np, P.N);
fprintf('    physical grid %d rows x %d cols\n\n', P.nRow, P.nCol);

%% ========================= 1. BUILD ===============================
if opt.Rebuild || ~isfile(mdlF)
    if opt.Rebuild
        if bdIsLoaded(mdl), close_system(mdl, 0); end
        if contains(path, genDir), rmpath(genDir); end
        if isfolder(genDir), rmdir(genDir, 's'); end
    end
    if ~isfolder(genDir), mkdir(genDir); end
    addpath(genDir);
    buildLibrary(P, genDir);
    buildModel(P, genDir, mdl, mdlF);
else
    addpath(genDir);
    fprintf('Using existing %s (pass ''Rebuild'',true to regenerate).\n\n', [mdl '.slx']);
end

if ~opt.Run
    if opt.Open, open_system(mdlF); end
    return
end

%% ========================== 2. RUN ================================
load_system(mdlF);
fprintf('Compiling and simulating (%d cells)...\n', P.N);
tSim = tic;
out  = sim(mdl, 'ReturnWorkspaceOutputs', 'on');
fprintf('  compile + solve: %.1f s wall clock\n', toc(tSim));

R = extractResults(out, P);
fprintf('  simulated %.0f s, %d samples on the viewer time base\n', R.t(end), numel(R.t));
fprintf('  Peak cell temperature   : %.1f degC\n', max(R.T(:)));
fprintf('  Peak spread across pack : %.1f K\n\n', max(max(R.T,[],1) - min(R.T,[],1)));

%% ========================= 3. VIEWER ==============================
showScrubber(R, P);

end % ======================= main =================================


%% ---------------------------------------------------------------
function P = defaultParams(opt)
%DEFAULTPARAMS  Everything tunable lives here.

P.Np        = 2;                 % cells per parallel assembly
P.nPaPerMod = opt.NPaPerMod;     % parallel assemblies per module
P.nMod      = opt.NMod;          % modules in the pack
P.Ns        = P.nPaPerMod * P.nMod;
P.N         = P.Ns * P.Np;

% Physical grid: each module is Np rows (the parallel group) x nPaPerMod cols,
% and modules stack in the row direction.  100s2p -> 20 x 10, the squarest
% arrangement available while every module stays a rectangle.
P.nRow = P.Np * P.nMod;
P.nCol = P.nPaPerMod;

% --- generic cylindrical 21700 NMC cell ---
P.D     = 21.55e-3;   % diameter                      [m]
P.H     = 70.15e-3;   % height                        [m]
P.mass  = 0.070;      % mass                          [kg]
P.cp    = 900;        % specific heat                 [J/kg/K]
P.Qnom  = 4.5;        % capacity                      [A*hr]
P.R25   = 0.022;      % DC resistance at 25 degC      [ohm]
P.kR    = -0.012;     % relative dR/dT                [1/K]

% --- packaging / heat transfer ---
P.pitch  = 23.0e-3;   % cell centre-to-centre spacing [m]
P.hConv  = 6.0;       % natural convection            [W/m^2/K]
P.emis   = 0.85;      % emissivity
P.Gcc    = 0.020;     % conduction, orthogonally adjacent cells  [W/K]
P.Gdiag  = 0.007;     % conduction, diagonally adjacent cells    [W/K]
P.shadow = 0.15;      % lateral area blocked per neighbouring cell
P.Arad   = 4.5e-4;    % radiation view area, orthogonal pairs    [m^2]
P.AradD  = 1.2e-4;    % radiation view area, diagonal pairs      [m^2]

% --- operating conditions ---
P.Tamb  = 25;         % ambient still air             [degC]
P.soc0  = 0.15;
P.Cchg  = 1.0;        % charge C-rate
P.Cdis  = 2.0;        % discharge C-rate
P.socHi = 0.95;
P.socLo = 0.10;
P.tRest0 = 60; P.tRestMid = 600; P.tRestEnd = 900;

% Three module variants are generated so that the two OUTER faces of the pack
% have no thermal node needing termination.  Foundation thermal blocks do not
% vectorise, so an exposed 1 x nCol face cannot be capped any other way.
P.libBase = 'batt21700';
if P.nMod == 1
    P.types = struct('name',{'ModuleSolo'}, 'xmin',{false}, 'xmax',{false});
elseif P.nMod == 2
    P.types = struct('name',{'ModuleTop','ModuleBot'}, ...
                     'xmin',{false,true}, 'xmax',{true,false});
else
    P.types = struct('name',{'ModuleTop','ModuleMid','ModuleBot'}, ...
                     'xmin',{false,true,true}, 'xmax',{true,true,false});
end
end


%% ---------------------------------------------------------------
function buildLibrary(P, genDir)
%BUILDLIBRARY  Battery Builder objects -> Simscape component libraries.

fprintf('Building Simscape Battery libraries...\n');

cm = batteryCellModelBlock;                     % Battery (Table-Based)
cm.BlockParameters.thermal_port = 'model';      % expose the cell thermal node
cm.BlockParameters.T_dependence = 'yes';        % temperature-dependent tables

geom  = batteryCylindricalGeometry(simscape.Value(P.H,'m'), ...
                                   simscape.Value(P.D/2,'m'));
cellO = batteryCell(geom, cm, ...
            Mass     = simscape.Value(P.mass,'kg'), ...
            Capacity = simscape.Value(P.Qnom,'A*hr'), ...
            Energy   = simscape.Value(P.Qnom*3.6,'W*hr'), ...
            Name     = "Cell21700");

mods = cell(1, numel(P.types));
for t = 1:numel(P.types)
    % Rows=Np makes the parallel group a COLUMN, so a module is a genuine
    % Np x nPaPerMod grid of cells rather than a 1-D strip.
    paO = batteryParallelAssembly(cellO, P.Np, Topology="Square", Rows=P.Np, ...
                                  ModelResolution="Detailed", Name="PA21700");
    paO.AmbientThermalPath            = 'CellBasedThermalResistance';
    paO.InterCellThermalPath          = 'on';
    paO.InterCellRadiativeThermalPath = 'on';

    modO = batteryModule(paO, P.nPaPerMod, ModelResolution="Detailed", ...
                         Name=P.types(t).name);
    modO.AmbientThermalPath            = 'CellBasedThermalResistance';
    modO.InterCellThermalPath          = 'on';   % cells inside a P-assembly
    modO.InterCellRadiativeThermalPath = 'on';
    if P.types(t).xmin, modO.XminThermalNodes = 'Vectorized'; end
    if P.types(t).xmax, modO.XmaxThermalNodes = 'Vectorized'; end
    mods{t} = modO;

    t0 = tic;
    buildBattery(modO, LibraryName=libOf(P,t), Directory=genDir, ...
                 MaskParameters="VariableNamesByType", ...
                 MaskInitialTargets="NumericValues", Verbose='off');
    fprintf('  %-11s built in %5.1f s\n', P.types(t).name, toc(t0));
    assert(isfile(fullfile(genDir,[libOf(P,t) '_lib.slx'])), ...
           'buildBattery did not produce %s_lib.slx', libOf(P,t));
end

% Topology of record: the equivalent Battery Builder pack object.
maO   = batteryModuleAssembly(mods{1}, CircuitConnection="Series", Name="ModuleAssembly");
packO = batteryPack(maO, Name="Pack");                               %#ok<NASGU>
m1 = mods{1};
fprintf('  cells per module %d, pack cells %d\n', m1.NumModels, P.N);
fprintf('  inter-cell connections per module        : %d\n', m1.NumInterCellThermalConnections);
fprintf('  inter-parallel-assembly conn. per module : %d\n\n', m1.NumInterParallelAssemblyThermalConnections);
end


%% ---------------------------------------------------------------
function s = libOf(P, t)
s = sprintf('%s_%s', P.libBase, lower(extractAfter(P.types(t).name, 'Module')));
end


%% ---------------------------------------------------------------
function ty = typeOfModule(P, k)
%TYPEOFMODULE  Which generated variant module k uses.
if numel(P.types) == 1
    ty = 1;
elseif k == 1
    ty = 1;
elseif k == P.nMod
    ty = numel(P.types);
else
    ty = 2;
end
end


%% ---------------------------------------------------------------
function pm = portMap(P, blk, ty)
%PORTMAP  Conserving-port indices for a generated module block.
%   Verified against the generated .ssc: left-side nodes come first in
%   declaration order (AmbH, then XminH), followed by the top node (+);
%   right-side nodes first (XmaxH), followed by the bottom node (-).

pm.amb = struct('side','LConn','i',1);
n = 1;
if P.types(ty).xmin
    n = n + 1;
    pm.xmin = struct('side','LConn','i',n);
end
pm.pos = struct('side','LConn','i',n+1);

m = 0;
if P.types(ty).xmax
    m = m + 1;
    pm.xmax = struct('side','RConn','i',m);
end
pm.neg = struct('side','RConn','i',m+1);

ph = get_param(blk,'PortHandles');
assert(numel(ph.LConn) == n+1 && numel(ph.RConn) == m+1, ...
   'Unexpected port count on %s: LConn=%d RConn=%d, expected %d and %d.', ...
   blk, numel(ph.LConn), numel(ph.RConn), n+1, m+1);
end


%% ---------------------------------------------------------------
function buildModel(P, genDir, mdl, mdlF)
%BUILDMODEL  Assemble the Simulink model around the generated module blocks.

fprintf('Assembling Simulink model...\n');
for t = 1:numel(P.types)
    load_system(fullfile(genDir,[libOf(P,t) '_lib.slx']));
end

if bdIsLoaded(mdl), close_system(mdl, 0); end
new_system(mdl); load_system(mdl);

x = 220; dy = 140;

% ---- modules -------------------------------------------------------
M = cell(1,P.nMod);  PM = cell(1,P.nMod);
for k = 1:P.nMod
    ty   = typeOfModule(P, k);
    src  = sprintf('%s_lib/%s', libOf(P,ty), P.types(ty).name);
    M{k} = sprintf('%s/Module%d', mdl, k);
    add_block(src, M{k}, 'Position', [x, 100+(k-1)*dy, x+100, 200+(k-1)*dy]);
    PM{k} = portMap(P, M{k}, ty);
end
pt = @(k,f) portOf(M{k}, PM{k}.(f).side, PM{k}.(f).i);

% ---- sources, references, sensors ---------------------------------
yBot = 100 + P.nMod*dy;
add_block('fl_lib/Electrical/Electrical Sources/Controlled Current Source', [mdl '/CCS'],  'Position',[60 100 100 160]);
add_block('fl_lib/Electrical/Electrical Elements/Electrical Reference',     [mdl '/EREF'], 'Position',[60 yBot 100 yBot+30]);
add_block('fl_lib/Electrical/Electrical Sensors/Voltage Sensor',            [mdl '/VS'],   'Position',[440 100 480 160]);
% Ambient air: a single-port absolute Temperature Source, so there is no
% reference-polarity ambiguity and no Simulink signal needed.
add_block('fl_lib/Thermal/Thermal Sources/Temperature Source',              [mdl '/AMB'],  'Position',[-90 300 -50 360]);
add_block('nesl_utility/Solver Configuration',                              [mdl '/SC'],   'Position',[-210 100 -170 130]);
add_block('nesl_utility/Simulink-PS Converter',                             [mdl '/I2PS'], 'Position',[-40 40 0 70]);
add_block('nesl_utility/PS-Simulink Converter',                             [mdl '/V2S'],  'Position',[540 110 580 140]);
add_block('simulink/Sources/From Workspace',                                [mdl '/Iref'], 'Position',[-180 35 -110 75]);
add_block('simulink/Sinks/To Workspace',                                    [mdl '/Vpack'],'Position',[620 110 680 140]);

set_param([mdl '/Iref'], 'VariableName','IpackTS', 'Interpolate','on', ...
          'OutputAfterFinalValue','Holding final value');
set_param([mdl '/AMB'], 'temperature', sprintf('%.4f', P.Tamb + 273.15), ...
          'temperature_unit', 'K');
set_param([mdl '/I2PS'], 'unit','A');
set_param([mdl '/V2S'],  'unit','V');
set_param([mdl '/Vpack'],'VariableName','Vpack','SaveFormat','StructureWithTime');

% ---- electrical: modules in series --------------------------------
% The source's "-" terminal feeds the pack "+", so a positive command drives
% current out of the pack, i.e. positive = discharge.
add_line(mdl, portOf([mdl '/CCS'],'RConn',2), pt(1,'pos'), 'autorouting','on');
for k = 1:P.nMod-1
    add_line(mdl, pt(k,'neg'), pt(k+1,'pos'), 'autorouting','on');
end
add_line(mdl, pt(P.nMod,'neg'), portOf([mdl '/EREF'],'LConn',1), 'autorouting','on');
add_line(mdl, portOf([mdl '/CCS'],'LConn',1), portOf([mdl '/EREF'],'LConn',1), 'autorouting','on');

% ---- thermal: chain the module faces ------------------------------
% This is what couples cells ACROSS module boundaries.  Module k's Xmax face
% carries one thermal node per parallel assembly; tying it to module k+1's
% Xmin face makes the whole pack a single connected grid of cell nodes.
for k = 1:P.nMod-1
    add_line(mdl, pt(k,'xmax'), pt(k+1,'xmin'), 'autorouting','on');
end

% ---- ambient node --------------------------------------------------
for k = 1:P.nMod
    add_line(mdl, portOf([mdl '/AMB'],'LConn',1), pt(k,'amb'), 'autorouting','on');
end

% ---- current command ----------------------------------------------
add_line(mdl, portOf([mdl '/Iref'],'Outport',1), portOf([mdl '/I2PS'],'Inport',1), 'autorouting','on');
add_line(mdl, portOf([mdl '/I2PS'],'RConn',1),   portOf([mdl '/CCS'],'RConn',1),   'autorouting','on');

% ---- voltage sensor + solver --------------------------------------
add_line(mdl, portOf([mdl '/VS'],'LConn',1), pt(1,'pos'), 'autorouting','on');
add_line(mdl, portOf([mdl '/VS'],'RConn',2), portOf([mdl '/EREF'],'LConn',1), 'autorouting','on');
add_line(mdl, portOf([mdl '/VS'],'RConn',1), portOf([mdl '/V2S'],'LConn',1), 'autorouting','on');
add_line(mdl, portOf([mdl '/V2S'],'Outport',1), portOf([mdl '/Vpack'],'Inport',1), 'autorouting','on');
add_line(mdl, portOf([mdl '/SC'],'RConn',1), portOf([mdl '/EREF'],'LConn',1), 'autorouting','on');

% ---- parameters ----------------------------------------------------
par     = cellParameters(P, genDir);
ambR    = ambientResistanceGrid(P);          % nRow x nCol, K/W
nPerMod = P.Np * P.nCol;
for k = 1:P.nMod
    rows = (k-1)*P.Np + (1:P.Np);            % this module's grid rows
    v    = zeros(1, nPerMod);
    for c = 1:P.nCol
        for lr = 1:P.Np
            v(P.Np*(c-1)+lr) = ambR(rows(lr), c);
        end
    end
    set_param(M{k}, 'AmbientResistance', mat2str(v, 6));
    % Initial targets are only honoured when their _specify flag is on;
    % otherwise the component's own default (SOC = 1) is used.
    set_param(M{k}, 'socCell_specify', 'on', 'socCell_priority', 'High', ...
              'socCell', sprintf('repmat(%.4f,%d,1)', P.soc0, nPerMod));
    set_param(M{k}, 'temperatureCell_specify', 'on', 'temperatureCell_priority', 'High', ...
              'temperatureCell', sprintf('repmat(%.4f,%d,1)', P.Tamb+273.15, nPerMod));
end

% ---- model workspace: parameter structs + current profile ---------
hws = get_param(mdl, 'ModelWorkspace');
f = fieldnames(par);
for i = 1:numel(f), assignin(hws, f{i}, par.(f{i})); end
[IpackTS, tEnd] = dutyCycle(P);
assignin(hws, 'IpackTS', IpackTS);

% ---- solver / logging ---------------------------------------------
set_param(mdl, 'Solver', 'daessc');
set_param(mdl, 'StopTime', sprintf('%.1f', tEnd));
set_param(mdl, 'RelTol', '1e-3');
set_param(mdl, 'AbsTol', '1e-4');
set_param(mdl, 'MaxStep', '5');
set_param(mdl, 'SimscapeLogType', 'all');
set_param(mdl, 'SimscapeLogName', 'simlog');
set_param(mdl, 'SimscapeLogDecimation', 1);
set_param(mdl, 'SaveOutput', 'on');
set_param(mdl, 'SaveFormat', 'Dataset');
set_param(mdl, 'PostLoadFcn', ...
    'addpath(fullfile(fileparts(which(bdroot)),''generated''));');

save_system(mdl, mdlF);
fprintf('  saved %s\n\n', [mdl '.slx']);
end


