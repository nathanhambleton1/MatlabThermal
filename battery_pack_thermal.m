function showScrubber(R, P)
%SHOWSCRUBBER  Top-down cell-temperature map with a time slider.

nRec = numel(R.t);
Tlo  = min(R.T(:));  Thi = max(R.T(:));
if Thi - Tlo < 1, Thi = Tlo + 1; end

fig = figure('Name', sprintf('Simscape %ds%dp 21700 pack', P.Ns, P.Np), ...
             'Color','w', 'Position',[60 60 1260 680]);

axG = axes('Parent',fig, 'Position',[0.05 0.20 0.40 0.66]);
im  = imagesc(axG, nan(P.nRow, P.nCol), [Tlo Thi]);
axis(axG,'image'); set(axG,'XTick',[],'YTick',[],'Box','on');
try
    colormap(axG, turbo);
catch
    colormap(axG, jet);
end
cbar = colorbar(axG); cbar.Label.String = 'Cell temperature [\circC]';
hold(axG,'on');
for k = 1:P.nMod-1                          % module boundaries
    y = k*P.Np + 0.5;
    plot(axG, [0.5 P.nCol+0.5], [y y], 'k-', 'LineWidth', 1.4);
end
ttl = title(axG, '', 'FontWeight','normal');

axT = axes('Parent',fig, 'Position',[0.56 0.58 0.39 0.33]);
tm = R.t/60;
hM = plot(axT, tm, max(R.T,[],1), 'r-','LineWidth',1.4); hold(axT,'on');
hA = plot(axT, tm, mean(R.T,1),   'k-','LineWidth',1.2);
hN = plot(axT, tm, min(R.T,[],1), 'b-','LineWidth',1.4);
yline(axT, P.Tamb, ':', 'ambient', 'HandleVisibility','off');
grid(axT,'on'); ylabel(axT,'T [\circC]');
legend(axT,[hM hA hN],{'max','mean','min'},'Location','northwest','Box','off');
title(axT,'Pack cell temperature (Simscape)','FontWeight','normal');
curT = xline(axT,0,'Color',[.3 .3 .3],'LineWidth',1.2,'HandleVisibility','off');

axI = axes('Parent',fig, 'Position',[0.56 0.20 0.39 0.28]);
yyaxis(axI,'left');  plot(axI, tm, R.I, 'LineWidth',1.4);
ylabel(axI,'I [A]  (+ = discharge)');
yyaxis(axI,'right'); plot(axI, R.tV/60, R.V, 'LineWidth',1.2);
ylabel(axI,'pack V');
grid(axI,'on'); xlabel(axI,'time [min]');
curI = xline(axI,0,'Color',[.3 .3 .3],'LineWidth',1.2);

sld = uicontrol(fig,'Style','slider','Units','normalized', ...
        'Position',[0.05 0.10 0.40 0.030],'Min',1,'Max',nRec,'Value',1, ...
        'SliderStep',[1/max(1,nRec-1) 20/max(1,nRec-1)]);
btn = uicontrol(fig,'Style','togglebutton','Units','normalized', ...
        'Position',[0.05 0.035 0.09 0.045],'String','Play','FontWeight','bold');
chk = uicontrol(fig,'Style','checkbox','Units','normalized', ...
        'Position',[0.16 0.040 0.29 0.035],'BackgroundColor','w', ...
        'String','Auto colour scale (per frame)', ...
        'Callback',@(~,~) draw(round(get(sld,'Value'))));
addlistener(sld,'ContinuousValueChange',@(s,~) draw(round(get(s,'Value'))));
set(sld,'Callback',@(s,~) draw(round(get(s,'Value'))));
set(btn,'Callback',@playCB);
draw(1);

    function draw(k)
        k  = max(1, min(nRec, k));
        Tk = reshape(R.T(R.gridIdx, k), P.nRow, P.nCol);
        set(im,'CData',Tk);
        if get(chk,'Value')
            lo = min(Tk(:)); hi = max(Tk(:));
            if hi-lo < 0.05, hi = lo+0.05; end
            set(axG,'CLim',[lo hi]);
        else
            set(axG,'CLim',[Tlo Thi]);
        end
        set(curT,'Value',R.t(k)/60); set(curI,'Value',R.t(k)/60);
        set(ttl,'String',{ ...
            sprintf('t = %.1f min   |   %s', R.t(k)/60, phaseAt(R.t(k), R.phases)), ...
            sprintf('T  min %.1f / mean %.1f / max %.1f \\circC', ...
                    min(Tk(:)), mean(Tk(:)), max(Tk(:)))});
        drawnow limitrate;
    end

    function playCB(src,~)
        if get(src,'Value')==1
            set(src,'String','Pause');
            k = round(get(sld,'Value'));
            while isvalid(src) && get(src,'Value')==1 && isvalid(fig)
                k = k+1; if k>nRec, k=1; end
                set(sld,'Value',k); draw(k); pause(0.02);
            end
            if isvalid(src), set(src,'String','Play'); end
        else
            set(src,'String','Play');
        end
    end
end


%% ---------------------------------------------------------------
function s = phaseAt(t, phases)
acc = 0; s = phases(end).name;
for k = 1:numel(phases)
    acc = acc + phases(k).dur;
    if t <= acc, s = phases(k).name; return; end
end
end
